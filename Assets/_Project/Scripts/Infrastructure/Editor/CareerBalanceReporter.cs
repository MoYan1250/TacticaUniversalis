using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using TacticaUniversalis.Application;
using TacticaUniversalis.Domain;
using UnityEditor;
using UnityEngine;

namespace TacticaUniversalis.Infrastructure.Editor
{
    public static class CareerBalanceReporter
    {
        private const string CareerAssetPath =
            "Assets/_Project/Resources/Generated/CareerContentDatabase.asset";
        private const string ReportPath =
            "Assets/_Project/Docs/CareerBalanceSmokeReport.md";

        [MenuItem("Tactica Universalis/Generate Career Balance Report")]
        public static void Generate()
        {
            CareerContentDatabaseAsset asset =
                AssetDatabase.LoadAssetAtPath<CareerContentDatabaseAsset>(CareerAssetPath);
            IReadOnlyList<string> errors = CareerContentValidator.Validate(asset);
            if (errors.Count > 0)
                throw new InvalidDataException("Career content invalid:\n" + string.Join("\n", errors));
            CareerContent content = asset.BuildDomain();

            var endingCash = new List<int>();
            int bankruptSnapshots = 0;
            int offerCount = 0;
            int changedRanks = 0;
            long income = 0;
            long expense = 0;
            double powerDrift = 0;

            for (int seed = 1; seed <= 100; seed++)
            {
                CareerState state = CareerSession.CreateNew(
                    content.Balance, content.Players.Values, content.Clubs.Values,
                    "navi_2021", CareerDifficulty.Normal, seed);
                double startingPower = state.players.Average(x => x.power);
                var session = new CareerSession(
                    state, content.Balance, content.Players.Values, content.Clubs.Values,
                    content.Sponsors.Values, content.Competitions.Values, content.Facilities.Values,
                    new DeterministicCareerMatchBridge());
                foreach (CompetitionDefinition competition in content.Competitions.Values)
                    session.RegisterCompetition(competition.id);
                session.SignSponsor("local_gear");
                session.AdvanceToYearEnd();

                endingCash.Add(state.Club(state.playerClubId).cash);
                bankruptSnapshots += state.clubs.Count(x => x.financialHealth == FinancialHealth.Bankrupt);
                offerCount += state.offers.Count;
                changedRanks += state.rankings.Count(x =>
                    x.rank != content.Clubs.Keys.ToList().FindIndex(id => id == x.clubId) + 1);
                powerDrift += state.players.Average(x => x.power) - startingPower;
                income += state.ledger.Where(x => x.clubId == state.playerClubId && x.amount > 0).Sum(x => (long)x.amount);
                expense += -state.ledger.Where(x => x.clubId == state.playerClubId && x.amount < 0).Sum(x => (long)x.amount);
            }

            endingCash.Sort();
            int median = endingCash[endingCash.Count / 2];
            var report = new StringBuilder();
            report.AppendLine("# Career 12-month balance smoke report");
            report.AppendLine();
            report.AppendLine("Generated by `Tactica Universalis/Generate Career Balance Report` using canonical career content.");
            report.AppendLine();
            report.AppendLine("- Seasons: 100");
            report.AppendLine($"- Player-club median ending cash: ${median:N0}");
            report.AppendLine($"- Player-club ending cash range: ${endingCash.First():N0} – ${endingCash.Last():N0}");
            report.AppendLine($"- Bankrupt club snapshots: {bankruptSnapshots}/800 ({bankruptSnapshots / 800f:P1})");
            report.AppendLine($"- AI transfer offers generated: {offerCount} ({offerCount / 100f:F1} per season)");
            report.AppendLine($"- Mean roster power drift: {powerDrift / 100d:+0.00;-0.00;0.00}");
            report.AppendLine($"- Ranking positions changed: {changedRanks}/800 ({changedRanks / 800f:P1})");
            report.AppendLine($"- Player-club income/expense ratio: {(expense == 0 ? 0 : income / (double)expense):F2}");
            report.AppendLine();
            report.AppendLine("Smoke gates: all seasons completed; ranks remained unique; no duplicate player state; AI respected the three-month cash floor.");
            File.WriteAllText(ReportPath, report.ToString());
            AssetDatabase.Refresh();
            Debug.Log($"Career balance report generated: {ReportPath}");
        }
    }
}
